function getStandardElement(sign: string): string {
  const raw = ELEMENT_MAP[sign] || 'Thổ';
  if (raw === 'Hoả') return 'Lửa';
  if (raw === 'Thổ') return 'Đất';
  if (raw === 'Thuỷ') return 'Nước';
  return 'Khí';
}

